// tools/vendor-projects.mjs — run BY HAND, never by the build: `node tools/vendor-projects.mjs`.
//
// /projects' pictures come from each project's own output, vendored into this repo with their provenance. This
// script is the only place the network is used for them (the font lesson in CLAUDE.md: a build that fetches
// fails when the far end changes). It resolves each source repo's HEAD to a commit, fetches the files AT that
// commit, and writes:
//   - src/data/vendor/{rlBhrpWealth,offchartPositioning,witnessFacets,macbootSections}.ts, each headed by its
//     source URL, commit, fetch date and this command;
//   - three raster captures into src/assets/projects/ (served through astro:assets as webp);
//   - manifold's two screensaver GIFs as MP4s into public/projects/ (the GIFs are deleted: they are 1.0-1.2 MB
//     each and a video is not an image), plus src/assets/projects/SOURCES.txt, the binaries' provenance.
//
// It FAILS rather than writes when a source is not what the page assumes — a CFTC series offchart's own rule
// would split, a table that lost its header, a character the site's mono subset cannot draw.
// Needs: `gh` authenticated as the owner (macboot is private), and `ffmpeg` on PATH.
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const OWNER = 'IngTian';
const COMMAND = 'node tools/vendor-projects.mjs';
const TODAY = new Date().toISOString().slice(0, 10);
const VENDOR = join(ROOT, 'src/data/vendor');
const ASSETS = join(ROOT, 'src/assets/projects');
const PUBLIC = join(ROOT, 'public/projects');

/** What the site's mono face (a latin subset) can draw — the same class tests/projectsListing.test.ts pins. */
const DRAWABLE = /^[\x20-\x7e\xa0-\xff–—‘’“”•…]*$/;

function fail(msg) {
  console.error(`vendor-projects: ${msg}`);
  process.exit(1);
}

const gh = (args, encoding = 'utf8') => execFileSync('gh', ['api', ...args], { encoding, maxBuffer: 64 << 20 });
const headOf = (repo) => gh([`repos/${OWNER}/${repo}/commits/HEAD`, '--jq', '.sha']).trim();
/** One file's bytes at `sha` — the raw media type, so binaries and files over 1 MB come through whole. */
const fileAt = (repo, sha, path) =>
  gh(['-H', 'Accept: application/vnd.github.raw', `repos/${OWNER}/${repo}/contents/${path}?ref=${sha}`], 'buffer');
const blobUrl = (repo, sha, path) => `https://github.com/${OWNER}/${repo}/blob/${sha}/${path}`;

// ── module writer ────────────────────────────────────────────────────────────────────────────────────────────

/** A TS literal, readable in a diff: anything short on one line, long primitive arrays wrapped near 116 columns,
 *  everything else one item a line. */
function lit(v, pad = '') {
  const inner = pad + '  ';
  const flat = JSON.stringify(v);
  if (v && typeof v === 'object' && inner.length + flat.length <= 116) return flat;
  if (Array.isArray(v)) {
    if (v.every((x) => typeof x !== 'object')) {
      const lines = [];
      let line = '';
      for (const x of v.map((x) => JSON.stringify(x))) {
        if (line && inner.length + line.length + x.length + 2 > 116) { lines.push(line); line = ''; }
        line += (line ? ' ' : '') + x + ',';
      }
      if (line) lines.push(line);
      return lines.length ? `[\n${lines.map((l) => inner + l).join('\n')}\n${pad}]` : '[]';
    }
    return `[\n${v.map((x) => inner + lit(x, inner) + ',').join('\n')}\n${pad}]`;
  }
  if (v && typeof v === 'object') {
    return `{\n${Object.entries(v).map(([k, x]) => `${inner}${k}: ${lit(x, inner)},`).join('\n')}\n${pad}}`;
  }
  return JSON.stringify(v);
}

function writeModule(file, name, type, value, header) {
  const lines = [
    `// src/data/vendor/${file} — GENERATED by tools/vendor-projects.mjs. Do not edit by hand; re-run the script.`,
    ...header.map((l) => (l ? `// ${l}` : '//')),
    `// fetched: ${TODAY}`,
    `// command: ${COMMAND}`,
  ];
  const path = join(VENDOR, file);
  writeFileSync(path, `${lines.join('\n')}\nexport const ${name}: ${type} = ${lit(value)};\n`);
  return path;
}

// ── rl-bhrp: the reproduction run's monthly out-of-sample returns ────────────────────────────────────────────

function rlBhrp() {
  const repo = 'rl-bhrp', path = 'results/shared-global/returns.csv', sha = headOf(repo);
  const [head, ...rows] = fileAt(repo, sha, path).toString('utf8').trim().split('\n').map((l) => l.split(','));
  const seedCols = head.flatMap((h, i) => (/^rl_seed\d+$/.test(h) ? [i] : []));
  const bhrp = head.indexOf('bhrp'), bench = head.indexOf('benchmark');
  if (head[0] !== '' || seedCols.length === 0 || bhrp < 0 || bench < 0) fail(`${path}: unexpected header ${head}`);
  const num = (s) => { const x = Number(s); if (!Number.isFinite(x)) fail(`${path}: not a number: "${s}"`); return x; };
  const value = {
    dates: rows.map((r) => r[0]),
    rlSeeds: seedCols.map((c) => rows.map((r) => num(r[c]))),
    bhrp: rows.map((r) => num(r[bhrp])),
    benchmark: rows.map((r) => num(r[bench])),
  };
  if (!value.dates.every((d) => /^\d{4}-\d{2}-\d{2}$/.test(d))) fail(`${path}: a row has no YYYY-MM-DD date`);
  return writeModule('rlBhrpWealth.ts', 'rlBhrpWealth',
    '{ dates: string[]; rlSeeds: number[][]; bhrp: number[]; benchmark: number[] }', value, [
      `source:  ${blobUrl(repo, sha, path)}`,
      `commit:  ${sha}`,
      '',
      'rl-bhrp\'s committed reproduction run (actor-centering "shared-global"): one simple monthly return per',
      `row, ${value.dates.length} months out of sample. rlSeeds[s][t] is seed s's return in month t, ${seedCols.length} seeds in`,
      'the CSV\'s column order. These are the REPRODUCTION\'s numbers, not the paper\'s Table 2 (profile.ts).',
    ]);
}

// ── offchart: CFTC positioning for one market, raw, so the method runs in tested code here ───────────────────

/** offchart lib/segments.py MAX_GAP_DAYS: a gap longer than this ends a segment. */
const MAX_GAP_DAYS = 91;

/** offchart lib/segments.py unit_signature(): the digits of contract_units, commas stripped first, so the API's
 *  two spellings of the same $100,000 contract agree. (Python's str.isdigit, on an ASCII field.) */
const unitSignature = (units) => (units ? String(units).replace(/,/g, '').replace(/[^0-9]/g, '') : '');

/** Every place offchart's segment_ids() would start a new segment, and why; empty means one segment. Only a
 *  change between two KNOWN signatures is a break: a null contract_units must not manufacture two breaks. */
function segmentBreaks(dates, units) {
  const breaks = [];
  let known = '';
  for (let i = 0; i < dates.length; i++) {
    const gap = i ? (Date.parse(dates[i]) - Date.parse(dates[i - 1])) / 864e5 : 0;
    if (gap > MAX_GAP_DAYS) breaks.push(`${dates[i]}: ${gap}-day gap`);
    const sig = unitSignature(units[i]);
    if (sig && known && sig !== known) breaks.push(`${dates[i]}: units ${known} -> ${sig}`);
    if (sig) known = sig;
  }
  return breaks;
}

async function offchart() {
  const code = '043602';
  const api = 'https://publicreporting.cftc.gov/resource/gpe5-46if.json';
  const query = '?$select=report_date_as_yyyy_mm_dd,market_and_exchange_names,open_interest_all,'
    + 'lev_money_positions_long,lev_money_positions_short,contract_units'
    + `&$where=cftc_contract_market_code=%27${code}%27&$order=report_date_as_yyyy_mm_dd&$limit=5000`;
  const res = await fetch(api + query);
  if (!res.ok) fail(`CFTC ${res.status} ${res.statusText}`);
  const rows = await res.json();
  if (rows.length === 0 || rows.length >= 5000) fail(`CFTC returned ${rows.length} rows (empty, or the limit truncated it)`);

  const weeks = rows.map((r) => r.report_date_as_yyyy_mm_dd.slice(0, 10));
  const int = (r, k) => { const x = Number(r[k]); if (!Number.isInteger(x)) fail(`CFTC ${r.report_date_as_yyyy_mm_dd}: ${k}="${r[k]}"`); return x; };
  for (let i = 1; i < weeks.length; i++) if (weeks[i] <= weeks[i - 1]) fail(`CFTC dates not strictly increasing at ${weeks[i]}`);
  const breaks = segmentBreaks(weeks, rows.map((r) => r.contract_units));
  if (breaks.length) fail(`the series is not one segment by offchart's rule:\n  ${breaks.join('\n  ')}`);

  const metricsSha = headOf('offchart');
  const value = {
    market: '10-year Treasury futures',
    cohort: 'Hedge funds',
    weeks,
    net: rows.map((r) => int(r, 'lev_money_positions_long') - int(r, 'lev_money_positions_short')),
    oi: rows.map((r) => int(r, 'open_interest_all')),
  };
  const spellings = [...new Set(rows.map((r) => r.contract_units))];
  return writeModule('offchartPositioning.ts', 'offchartPositioning',
    '{ market: string; cohort: string; weeks: string[]; net: number[]; oi: number[] }', value, [
      `source:  ${api} (CFTC Traders in Financial Futures, futures only)`,
      `query:   ${query}`,
      `commit:  ${metricsSha} (IngTian/offchart, whose method src/lib/positioning.ts ports)`,
      '',
      `Market ${code}, "${rows.at(-1).market_and_exchange_names}" on the latest report: ${weeks.length} weekly reports,`,
      `${weeks[0]} to ${weeks.at(-1)}. net = lev_money_positions_long - lev_money_positions_short (the`,
      'leveraged-funds cohort, which offchart labels "Hedge funds"); oi = open_interest_all. RAW positions: the',
      'share and its percentile are computed in tested code, not here.',
      `ONE SEGMENT by offchart's rule (no gap over ${MAX_GAP_DAYS} days, one unit signature, checked when written):`,
      `contract_units arrives as ${spellings.length} spelling(s) of one contract: ${spellings.map((s) => JSON.stringify(s)).join(', ')}.`,
    ]);
}

// ── witness: an excerpt of its committed example output ──────────────────────────────────────────────────────

function witness() {
  const repo = 'witness', path = 'examples/carney-market/sample-output/facets.md', sha = headOf(repo);
  const text = fileAt(repo, sha, path).toString('utf8');
  const hdr = text.match(/^(\d+) facets distilled from (\d+) observations\.$/m);
  if (!hdr) fail(`${path}: no "N facets distilled from M observations." line`);
  const all = [...text.matchAll(/^### (\S+)\nconfidence ([\d.]+), (\d+) observations?$/gm)]
    .map((m) => ({ name: m[1], confidence: Number(m[2]), observations: Number(m[3]) }));
  if (all.length !== Number(hdr[1])) fail(`${path}: header says ${hdr[1]} facets, parsed ${all.length}`);
  // Array.prototype.sort is stable, so a tie keeps the file's order.
  const top = [...all].sort((a, b) => b.observations - a.observations).slice(0, 5);
  if (!top.every((f) => DRAWABLE.test(f.name))) fail(`${path}: a facet name the mono subset cannot draw`);
  return writeModule('witnessFacets.ts', 'witnessFacets',
    '{ facets: number; observations: number; top: { name: string; confidence: number; observations: number }[] }',
    { facets: Number(hdr[1]), observations: Number(hdr[2]), top }, [
      `source:  ${blobUrl(repo, sha, path)}`,
      `commit:  ${sha}`,
      '',
      'The file\'s header line, and its five most-observed facets (ties in file order). An excerpt of distilled',
      'facets, NOT a dated history: that directory holds no history to draw (spec section 6).',
    ]);
}

// ── macboot: its README's table of sections ──────────────────────────────────────────────────────────────────

function macboot() {
  const repo = 'macboot', path = 'README.md', sha = headOf(repo);
  const lines = fileAt(repo, sha, path).toString('utf8').split('\n');
  const at = lines.findIndex((l) => /^\|\s*§\s*\|\s*category\s*\|\s*what\s*\|$/.test(l.trim()));
  if (at < 0) fail(`${path}: no "| § | category | what |" table`);
  const rows = [];
  for (const l of lines.slice(at + 2)) {
    if (!l.startsWith('|')) break;
    const cells = l.split('|').slice(1, -1).map((c) => c.replace(/\*\*|`/g, '').trim());
    if (cells.length !== 3) fail(`${path}: table row without three cells: ${l}`);
    // The README marks a by-hand section with 👤. Rendered as words; dropped where the name already says so
    // ("By hand 👤" would otherwise read "By hand (by hand)").
    cells[1] = cells[1].replace(/\s*👤/u, /by hand/i.test(cells[1]) ? '' : ' (by hand)');
    if (!cells.every((c) => DRAWABLE.test(c))) fail(`${path}: a character the mono subset cannot draw: ${cells}`);
    rows.push(cells);
  }
  if (rows.length === 0) fail(`${path}: the section table is empty`);
  return writeModule('macbootSections.ts', 'macbootSections', '{ rows: [string, string, string][] }', { rows }, [
    `source:  ${blobUrl(repo, sha, path)} (a PRIVATE repo; this table is the excerpt the page shows)`,
    `commit:  ${sha}`,
    '',
    'The README\'s table of sections, [section, category, what] per row: its by-hand marker (an emoji, U+1F464)',
    'written as "(by hand)", or dropped where the name already says it, and its markdown emphasis stripped.',
  ]);
}

// ── the binaries: captures and manifold's motion ─────────────────────────────────────────────────────────────

function binaries() {
  const tmp = mkdtempSync(join(tmpdir(), 'vendor-projects-'));
  const sources = [];
  const shas = {};
  const sha = (repo) => (shas[repo] ??= headOf(repo));
  const record = (out, repo, path) => {
    sources.push(`${out.slice(ROOT.length)}  ${statSync(out).size} B  <- ${blobUrl(repo, sha(repo), path)}`);
    return out;
  };
  const written = [];
  for (const [repo, path, name] of [
    ['trading-desk', 'assets/dashboard.png', 'trading-desk-dashboard.png'],
    ['daylogs', 'assets/body.png', 'daylogs-body.png'],
    ['manifold', 'Resources/thumbnail@2x.png', 'manifold-thumbnail.png'],
  ]) {
    const out = join(ASSETS, name);
    writeFileSync(out, fileAt(repo, sha(repo), path));
    written.push(record(out, repo, path));
  }
  for (const theme of ['dark', 'light']) {
    const path = `docs/saver-${theme}.gif`;
    const gif = join(tmp, `saver-${theme}.gif`);
    writeFileSync(gif, fileAt('manifold', sha('manifold'), path));
    console.log(`  ${path} (deleted after conversion)  ${statSync(gif).size} B`);
    const out = join(PUBLIC, `manifold-saver-${theme}.mp4`);
    execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', gif, '-movflags', '+faststart', '-pix_fmt', 'yuv420p',
      '-vf', 'scale=trunc(iw/2)*2:trunc(ih/2)*2', out], { stdio: 'inherit' });
    written.push(record(out, 'manifold', path));
  }
  rmSync(tmp, { recursive: true, force: true });
  const txt = join(ASSETS, 'SOURCES.txt');
  writeFileSync(txt, [
    'Provenance of /projects\' vendored binaries. GENERATED by tools/vendor-projects.mjs; re-run it, do not edit.',
    `fetched: ${TODAY}`,
    `command: ${COMMAND}`,
    'The MP4s are the GIFs converted with: ffmpeg -i in.gif -movflags +faststart -pix_fmt yuv420p '
      + '-vf "scale=trunc(iw/2)*2:trunc(ih/2)*2" out.mp4',
    '',
    ...sources,
    '',
  ].join('\n'));
  return written;
}

